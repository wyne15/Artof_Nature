// Usage: npm run seed:sql   (writes supabase/seed.sql)
import { writeFileSync } from "node:fs";
import { SEED_PRODUCTS } from "../src/data/seed-products.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = SEED_PRODUCTS.map(
  (p) =>
    `(${[p.slug, p.category, p.nameEn, p.nameRo, p.noteEn, p.noteRo, p.descEn, p.descRo, p.formatEn, p.formatRo].map(q).join(", ")}, ${p.pricePence}, ${p.stock}, true, ${q(p.tag)}, ${q(p.artKind)}, ${q(p.artColor)}, ${q(p.artWax)}, ${p.sort})`,
);
const sql = `-- Generated by scripts/make-seed.ts. Run after schema.sql. Safe to re-run: existing slugs are left untouched.
insert into public.products
 (slug, category, name_en, name_ro, note_en, note_ro, desc_en, desc_ro, format_en, format_ro, price_pence, stock, active, tag, art_kind, art_color, art_wax, sort)
values
${rows.join(",\n")}
on conflict (slug) do nothing;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("supabase/seed.sql written (" + SEED_PRODUCTS.length + " products)");
